def _subscribe_granted_users() -> None:
    """Non-admin accounts that had any feature keep working: "Bạn bè" plan, no expiry."""
    conn = op.get_bind()
    plan_id = conn.execute(sa.text("SELECT id FROM plans WHERE code = :c"), {"c": MIGRATED_PLAN}).scalar_one()
    users = conn.execute(sa.text("SELECT id, features FROM users WHERE is_admin = :f"), {"f": False}).all()
    now = datetime.now(UTC).replace(tzinfo=None)
    for user_id, features in users:
        granted = json.loads(features) if isinstance(features, str) else (features or [])
        if not granted:
            continue  # was waiting for approval: stays pending
        conn.execute(
            sa.text(
                "INSERT INTO subscriptions (user_id, plan_id, starts_at, expires_at, status, note, source, created_at)"
                " VALUES (:u, :p, :now, NULL, 'active', :note, 'admin', :now)"
            ),
            {"u": user_id, "p": plan_id, "now": now, "note": "Chuyển từ quyền cũ: " + ", ".join(granted)},
        )


def _restore_feature_grants() -> None:
    """Downgrade: admins get every feature, others the features of their active plan."""
    conn = op.get_bind()
    conn.execute(sa.text("UPDATE users SET features = :f WHERE is_admin = :t"), {"f": json.dumps(ALL_FEATURES), "t": True})
    rows = conn.execute(
        sa.text(
            "SELECT s.user_id, p.features FROM subscriptions s JOIN plans p ON p.id = s.plan_id"
            " WHERE s.status = 'active'"
        )
    ).all()
    for user_id, features in rows:
        value = features if isinstance(features, str) else json.dumps(features)
        conn.execute(sa.text("UPDATE users SET features = :f WHERE id = :u AND is_admin = :n"),
                     {"f": value, "u": user_id, "n": False})
